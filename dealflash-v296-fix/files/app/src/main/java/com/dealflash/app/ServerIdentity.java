package com.dealflash.app;

import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.text.Normalizer;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Java port of the Worker's product identity (server src/core.js, frozen at v2.9.5 behaviour).
 *
 * The server key for a Fallcent product is {@code fcfp:} + sha1(productFingerprintText(cleanProductTitle(title)))[0..20].
 * The app NEVER derives keys for server-origin rows; it trusts the {@code product_key} it was given. This port exists only to
 * (a) fold ephemeral legacy keys ({@code fc:l:}) onto the same key the server now uses and (b) re-key rows stored by older
 * app versions. {@code tests/fixtures/identity-vectors.json} is generated by the server and replayed here, so any drift fails CI.
 */
public final class ServerIdentity {
    private ServerIdentity() {}

    private static final int U = Pattern.UNICODE_CHARACTER_CLASS;
    private static final Pattern WS = Pattern.compile("\\s+", U);
    private static final Pattern PRICE_TAIL = Pattern.compile("\\s*[0-9][0-9,]{2,}\\s*원\\s*[▼↓]\\s*[0-9]{1,3}\\s*%\\s*$", U);
    private static final Pattern EMOJI = Pattern.compile("[🔥🚀⚡💥⭐★]+");
    private static final Pattern PROMO = Pattern.compile("^(?:구매\\s*타이밍|지금이\\s*타이밍|역대급\\s*최저가|역대급|최저가\\s*타이밍|타이밍|오늘의\\s*특가|초특가|특가|핫딜|추천상품|득템|놓치면\\s*후회|구매)(?=\\s|$)\\s*", U);
    private static final Pattern BADGE = Pattern.compile("(?:\\[)?(?:판매자\\s*로켓|로켓\\s*배송|로켓배송|로켓프레시|로켓직구)(?:\\])?(?=\\s|$)", U);
    private static final Pattern SPEC_JOIN = Pattern.compile("([0-9]+(?:\\.[0-9]+)?\\s*(?:ml|kg|g|l))\\s*[, ]+\\s*([0-9]+개)", U | Pattern.CASE_INSENSITIVE);
    private static final Pattern UNIT_GLUE = Pattern.compile("([0-9])\\s+(ml|l|g|kg|tb|gb|cm|mm|인치|개|매|팩|봉|병|캔|세트|입)(?=$|[^a-z])", U);
    private static final Pattern NON_WORD = Pattern.compile("[^가-힣a-z0-9]+");
    private static final Pattern TAIL_REPEAT = Pattern.compile("(\\S+(?:\\s+\\S+){0,3}?)\\s+\\1$", U);
    private static final Pattern SEG_SPLIT = Pattern.compile("\\s*,\\s+", U);
    private static final Pattern X_TIMES_Q = Pattern.compile("^(.+?)\\s*[×x]\\s*(\\d+(?:\\.\\d+)?\\s*(?:개입|개|세트|팩|봉|병|캔|매|입|ea|p))$", U | Pattern.CASE_INSENSITIVE);

    private static String trim(String s) { return WS.matcher(s).replaceAll(" ").trim(); }
    private static String nfkc(String s) { return Normalizer.normalize(s, Normalizer.Form.NFKC); }

    /** == cleanProductTitle() */
    public static String cleanTitle(String input) {
        String in = input == null ? "" : input;
        String x = trim(nfkc(in));
        x = PRICE_TAIL.matcher(x).replaceFirst("").trim();
        x = EMOJI.matcher(x).replaceAll(" ").trim();
        String prev = null;
        while (!x.equals(prev)) { prev = x; x = PROMO.matcher(x).replaceFirst("").trim(); }
        x = BADGE.matcher(x).replaceAll(" ");
        x = trim(SPEC_JOIN.matcher(x).replaceAll("$1 × $2"));
        return x.isEmpty() ? in.trim() : x;
    }

    /** == normalizeProductTitle() */
    public static String normalize(String input) {
        String x = nfkc(cleanTitle(input)).toLowerCase(Locale.ROOT);
        x = x.replace('×', 'x').replace('＊', 'x');
        x = UNIT_GLUE.matcher(x).replaceAll("$1$2");
        return trim(NON_WORD.matcher(x).replaceAll(" "));
    }

    /** == productFingerprintText() */
    public static String fingerprint(String input) {
        String x = normalize(input), prev = null;
        while (!x.equals(prev)) { prev = x; x = TAIL_REPEAT.matcher(x).replaceFirst("$1").trim(); }
        return x;
    }

    /** Server key for a Fallcent title without a product id, or "" when the title is too weak to identify anything. */
    public static String keyFor(String title) {
        String fp = fingerprint(title);
        return fp.length() >= 8 ? "fcfp:" + sha1(fp, 20) : "";
    }

    /** == displayProductTitle(): one copy of the repeated option/quantity text. Display only, never identity. */
    public static String displayTitle(String input) {
        String base = cleanTitle(input);
        String[] raw = SEG_SPLIT.split(base);
        List<String> segs = new ArrayList<>();
        for (String s : raw) { String t = s.trim(); if (!t.isEmpty()) segs.add(t); }
        if (segs.size() < 2) return base;
        List<String> out = new ArrayList<>();
        for (String s : segs) {
            boolean dup = false;
            for (String o : out) if (dispKey(o).equals(dispKey(s))) { dup = true; break; }
            if (!dup) out.add(s);
        }
        int i = out.size() - 1;
        while (i >= 2) {
            Matcher m = X_TIMES_Q.matcher(out.get(i));
            if (m.find()) {
                String xk = dispKey(m.group(1)), qk = dispKey(m.group(2));
                int before = out.size();
                List<String> kept = new ArrayList<>();
                for (int j = 0; j < out.size(); j++) {
                    String o = out.get(j);
                    if (j == 0 || j >= i || !(dispKey(o).equals(xk) || dispKey(o).equals(qk))) kept.add(o);
                }
                out = kept;
                i -= before - out.size();
            }
            i--;
        }
        return out.size() == segs.size() ? base : String.join(", ", out);
    }

    private static String dispKey(String s) { return WS.matcher(nfkc(s).toLowerCase(Locale.ROOT)).replaceAll(""); }

    /** Keys that carried an ephemeral share token and can never be refreshed by the server. */
    public static boolean isEphemeralKey(String key) { return key != null && (key.startsWith("fc:l:") || key.startsWith("fcshort:")); }

    private static String sha1(String s, int chars) {
        try {
            byte[] d = MessageDigest.getInstance("SHA-1").digest(s.getBytes(StandardCharsets.UTF_8));
            StringBuilder b = new StringBuilder();
            for (byte x : d) b.append(String.format(Locale.ROOT, "%02x", x));
            return b.substring(0, Math.min(chars, b.length()));
        } catch (Exception e) { throw new IllegalStateException(e); }
    }
}
